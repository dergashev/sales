/**
 * Изъятие внутренних ссылок из клиентской копии (MODE-001, дефект 13).
 *
 * Нормативные коды (`CALC-004`, `R-18`, `VARIANT-001`, `XSC-08`) — это
 * доказательная база подготовки, а не язык переговоров. Во внутреннем
 * пространстве они полезны: продавец и аудитор проходят по ним к правилу.
 * На клиентской поверхности они мусор в лучшем случае и утечка реестра
 * требований — в худшем.
 *
 * Почему изъятие, а не второй текст. Второй текст — это второй источник:
 * копии расходятся при первой же правке, и расходятся молча (тот же класс,
 * что «одна сущность, два имени»). Здесь одна строка, из которой в
 * презентации механически удаляется ссылочный хвост; словарь EN при этом
 * остаётся единственным и переводит ровно ту же строку.
 *
 * Границы намеренно узкие: снимается ТОЛЬКО скобочная группа, целиком
 * состоящая из кодов вида `ABC-123` через запятую. Осмысленный текст в
 * скобках (`(Sand/Kies, Baugrundgutachten unbedenklich)`) не трогается —
 * иначе изъятие начало бы съедать содержание.
 */

const RX_REF_GROUP = /\s*\((?:[A-ZÄÖÜ][A-Z0-9-]*-\d{2,3})(?:\s*[,·/]\s*[A-ZÄÖÜ][A-Z0-9-]*-\d{2,3})*\)/g

export function stripInternalRefs(text: string): string {
  return text.replace(RX_REF_GROUP, '')
}

/** Клиентская поверхность не цитирует реестр; внутренняя — цитирует. */
export function copyFor(text: string, mode: 'intern' | 'praesentation'): string {
  return mode === 'praesentation' ? stripInternalRefs(text) : text
}
