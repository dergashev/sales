/**
 * Как называется Option и как это имя читается.
 *
 * Имена хранятся строками, а строки не переводятся: немецкое имя осталось бы
 * немецким в английском интерфейсе. Поэтому автоматическое имя — это МАРКЕР
 * «человек имя не выбирал», а перевод происходит там, где имя читают.
 *
 * Модуль отдельный, потому что имя нужно и редьюсеру (`store`), и экранам, а
 * `store` импортирует из `optionLifecycle` ровно две функции — это проверяется
 * тестом, и расширять тот импорт значит ломать проверку, которая существует не
 * зря: селектор жизненного цикла не должен быть достижим из редьюсера.
 */

/** Маркер, под которым создаётся первая Option проекта в `v3`/`v4`. */
export const BASE_OPTION_AUTO_NAME = 'Base option'

/**
 * Имя базовой Option, которое человек не выбирал.
 *
 * Два значения, а не одно: до появления базовой Option первая называлась
 * «Option 1», и проекты с таким именем существуют. Оба читаются как «имя не
 * задано», поэтому оба показываются под переведённой подписью.
 */
export function isAutoBaseName(name: string): boolean {
  return name === BASE_OPTION_AUTO_NAME || name === 'Option 1'
}

/** Подпись строки: собственное имя базовой Option либо сохранённое имя. */
export function optionDisplayName(
  row: { name: string; isBase: boolean }, baseLabel: string,
): string {
  return row.isBase && isAutoBaseName(row.name) ? baseLabel : row.name
}
